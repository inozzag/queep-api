#!/usr/bin/env python3
"""Run interactively: keeps credentials out of chat, argv, Git and build logs."""

import getpass
import os
import re
import secrets
from pathlib import Path


def write_private(path, content):
    fd = os.open(path, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
    os.fchmod(fd, 0o600)
    with os.fdopen(fd, "w") as stream:
        stream.write(content)


def main():
    root = Path(__file__).resolve().parents[1]
    print("Configuração de TESTE do Queep. Não ativa cobrança nem altera a nuvem.")
    public = getpass.getpass("Chave pública do RevenueCat Test Store (test_...): ").strip()
    server = getpass.getpass("Chave secreta da API RevenueCat V1 (sk_...): ").strip()
    if not re.fullmatch(r"test_[A-Za-z0-9]+", public):
        raise SystemExit("Chave Test Store inválida.")
    if not re.fullmatch(r"sk_[A-Za-z0-9]+", server):
        raise SystemExit("Chave secreta V1 inválida.")
    billing = root / ".env.billing"
    existing = billing.read_text() if billing.exists() else ""
    previous = re.search(r"^REVENUECAT_WEBHOOK_TOKEN=(.+)$", existing, re.MULTILINE)
    token = previous.group(1) if previous else secrets.token_urlsafe(32)
    write_private(billing, "QUEEP_BILLING_MODE=required\nQUEEP_BILLING_ACCEPT_SANDBOX=true\n"
                  "REVENUECAT_ENTITLEMENT=queep_pro\n"
                  f"REVENUECAT_API_KEY={server}\nREVENUECAT_WEBHOOK_TOKEN={token}\n")
    apple = root.parent / "queep-apple/Config/BillingDevelopment.xcconfig"
    write_private(apple, "// Development only; generated by configure-revenuecat.py\n"
                  f"QUEEP_REVENUECAT_IOS_KEY = {public}\n"
                  f"QUEEP_REVENUECAT_MAC_KEY = {public}\n")
    print("Configuração salva em arquivos locais ignorados pelo Git.")
    print("Avise o Codex para validar a integração de teste. Não cole as chaves no chat.")


if __name__ == "__main__":
    main()
